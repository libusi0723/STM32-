//====================================================
// 波形更新
//====================================================
void Wave_Update(void)
{
    u16 value = 2048;
    u16 peak;
    static u16 index = 0;

    peak = (u16)(2047UL * amplitude / 100);
    
    //------------------------------------------------
    // 正弦波
    //------------------------------------------------
    if(wave_type == 0)
    {
       value = 2048 + ((sine_table[index] - 2048) * amplitude / 100);
    } 
     
    //------------------------------------------------
    // 方波
    //------------------------------------------------
    else if(wave_type == 1)
    {
        if(index < TABLE_SIZE / 2)
            value = 2048 + peak;
        else
            value = 2048 - peak;
    }

    //------------------------------------------------
    // 三角波
    //------------------------------------------------
    else if(wave_type == 2)
    {
        if(index < 256/ 2)
        {
            value = (2048 - peak) +
                    (u32)(2 * peak) * index / (TABLE_SIZE / 2);
        }
        else
        {
            value = (2048 + peak) -
                    (u32)(2 * peak) *
                    (index - TABLE_SIZE / 2) /
                    (TABLE_SIZE / 2);
        }
    }

    //------------------------------------------------
    // 限幅保护
    //------------------------------------------------
    if(value > 4095)
        value = 4095;

    DAC_SetValue(value);

    //------------------------------------------------
    // 更新索引
    //------------------------------------------------
    index++;

    if(index >= TABLE_SIZE)
        index = 0;
}


//====================================================
// TIM2频率更新
//====================================================
void TIM2_Freq_Update(void)
{
    u16 psc = 71;
    u32 temp;

    temp = 72000000 / (psc + 1);

    temp = temp / (freq * TABLE_SIZE);

    if(temp > 0)
        temp--;

    if(temp > 65535)
        temp = 65535;

    TIM2->PSC = psc;
    TIM2->ARR = (u16)temp;
    TIM2->CNT = 0;
}